import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {runExistingSeoPilot} from '../runtime/seo-phase2-pilot-runner-v1.mjs';
import {inspectSeoTrainingIntake} from '../runtime/seo-phase2-training-intake-v1.mjs';
test('actual source-grounded written pilot flows through durable JOB-001 and replays without duplicate or certification',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'seo-pilot-journal-'));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const journal_path=path.join(root,'job001.v8');
 const a=runExistingSeoPilot({journal_path});
 assert.equal(a.status,'PROFESSIONAL_EXAMPLE_CAPTURED_JOB001_NOT_AGENT_TRAINED');
 assert.equal(a.role_id,'SEO-D05:SPECIALIST:01');
 assert.equal(a.case_id,'SEO-D05:SPECIALIST:01:EXAM:01');
 assert.equal(a.post_id,1098);
 assert.equal(a.model_api_calls,0);
 assert.equal(a.external_fetches,0);
 assert.equal(a.distinct_agent_identity_authenticated,false);
 assert.equal(a.qa_d31_passed,false);
 assert.equal(a.d32_training_certified,false);
 assert.equal(a.tribunal_accepted,false);
 assert.equal(a.prod_departments_certified,0);
 assert.equal(a.external_writes,0);
 const b=runExistingSeoPilot({journal_path});
 assert.deepEqual(b,a);
 const inspect=inspectSeoTrainingIntake({file_path:journal_path,job_id:a.journal_job_id});
 assert.equal(inspect.completed,true);
 assert.equal(inspect.pending_real_identity,true);
 assert.equal(inspect.answer_sha256,a.answer_sha256);
});
