/**
 * CEREBRO P0-A · pure test-lifecycle core · isolated LAB only.
 * Accepts trusted server-created Supabase clients. Never receives production
 * secrets or invokes any network in module initialization. No console/log calls.
 * Return only static status codes; never return tokens, email, IDs or errors.
 */
const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const REF='hnqlnvakzaywtafeiybt';
const ISSUER='https://'+REF+'.supabase.co/auth/v1';
const INVALID_SESSION='00000000-0000-4000-8000-000000000002';
const INVALID_USER='00000000-0000-4000-8000-000000000001';
const STAGES=new Set(['PREFLIGHT','CREATE','SIGN_IN','CLAIMS','NEGATIVES','ACTIVE','LOGOUT','REVOKED','COMPLETE']);
const safe=(passed,stage,cleanup)=>Object.freeze({
 status:passed&&cleanup!=='FAILED'?'PASS':'FAIL',
 stage:STAGES.has(stage)?stage:'CREATE',
 cleanup_status:cleanup,
 issuer_scope:'LAB_ISSUER_ONLY',
 real_owner_prod_certified:false,
 secrets_in_result:false
});
const validClient=c=>c&&typeof c==='object';
/**
 * @param {{admin:object,userClient:object,email:string,password:string,
 *   now?:()=>number,sleep?:(ms:number)=>Promise<void>}} input
 * The credentials are generated by a private caller, never returned.
 */
export async function runOfficialLabSessionCycle(input={}){
 const {admin,userClient,email,password,now=Date.now,
   sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms))}=input;
 if(!validClient(admin)||!validClient(userClient)||
    typeof admin.auth?.admin?.createUser!=='function'||
    typeof admin.auth.admin.deleteUser!=='function'||
    typeof admin.rpc!=='function'||
    typeof userClient.auth?.signInWithPassword!=='function'||
    typeof userClient.auth.getClaims!=='function'||
    typeof userClient.auth.signOut!=='function'||
    typeof email!=='string'||!/^cerebro-p0a-[a-f0-9]{32}@example\.invalid$/.test(email)||
    typeof password!=='string'||password.length<30||
    typeof now!=='function'||typeof sleep!=='function')
   return safe(false,'CREATE','NOT_NEEDED');
 let userId=null,sessionOpened=false,loggedOut=false,passed=false,stage='PREFLIGHT';
 let cleanup='NOT_NEEDED',failedCleanupSignout=false;
 const check=async(sid,uid)=>{
  const {data,error}=await admin.rpc('cerebro_operativa_session_guard_lab_v0',
    {p_session_id:sid,p_user_id:uid});
  if(error||typeof data!=='boolean')throw Error('PRIVATE_READ_FAILED');
  return data;
 };
 try{
  // Verify this is an internally authorised LAB reader *before* creating
  // any temporary Auth user. This single fixed, negative RPC leaks no session
  // metadata and cannot pass with a publishable/anon key.
  if(await check(INVALID_SESSION,INVALID_USER)!==false)
   throw Error('LAB_READER_PREFLIGHT_DENIED');
  stage='CREATE';
  const created=await admin.auth.admin.createUser({email,password,email_confirm:true,
   app_metadata:{cerebro_lab_only_test:'p0a_auth_session_v1'}});
  if(UUID.test(created?.data?.user?.id||''))userId=created.data.user.id;
  if(created?.error||!userId)throw Error('CREATE_FAILED');
  stage='SIGN_IN';
  const sign=await userClient.auth.signInWithPassword({email,password});
  const token=sign?.data?.session?.access_token;
  if(sign?.error||typeof token!=='string'||token.length<20)throw Error('SIGN_IN_FAILED');
  sessionOpened=true;
  stage='CLAIMS';
  const checked=await userClient.auth.getClaims(token);
  const claims=checked?.data?.claims;
  if(checked?.error||!claims||claims.iss!==ISSUER||
     claims.sub!==userId||!UUID.test(claims.session_id||'')||
     claims.aud!=='authenticated'||claims.role!=='authenticated'||
     !Number.isFinite(claims.exp)||claims.exp*1000<=now())
    throw Error('INVALID_CLAIMS');
  stage='NEGATIVES';
  if(await check(INVALID_SESSION,userId)!==false||
     await check(claims.session_id,INVALID_USER)!==false)
    throw Error('NEGATIVE_NOT_DENIED');
  stage='ACTIVE';
  if(await check(claims.session_id,userId)!==true)throw Error('ACTIVE_NOT_FOUND');
  stage='LOGOUT';
  const logout=await userClient.auth.signOut({scope:'local'});
  if(logout?.error)throw Error('LOGOUT_FAILED');
  loggedOut=true;
  stage='REVOKED';
  let rejected=false;
  for(let i=0;i<3;i++){
   if(await check(claims.session_id,userId)===false){rejected=true;break}
   if(i<2)await sleep(300);
  }
  if(!rejected)throw Error('REVOCATION_NOT_CONFIRMED');
  stage='COMPLETE';passed=true;
 }catch{
  // Do not propagate SDK errors: they can include PII or bearer token fragments.
 }finally{
  if(sessionOpened&&!loggedOut){
   try{
    const result=await userClient.auth.signOut({scope:'local'});
    if(result?.error)failedCleanupSignout=true;
    else loggedOut=true;
   }catch{failedCleanupSignout=true}
  }
  if(userId){
   try{
    const result=await admin.auth.admin.deleteUser(userId);
    cleanup=result?.error?'FAILED':'DONE';
   }catch{cleanup='FAILED'}
  }
  if(failedCleanupSignout)cleanup='FAILED';
 }
 return safe(passed,stage,cleanup);
}
