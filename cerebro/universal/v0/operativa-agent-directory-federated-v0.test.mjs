import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import roles from '../../registry/role-agent-registry.v1.json' with {type:'json'};
import social from '../../registry/social-facebook-agent-role-design.v1.json' with {type:'json'};
import master from '../../registry/engine-registry.v1.json' with {type:'json'};
const read=(name)=>readFileSync(new URL('../../../'+name,import.meta.url),'utf8');
test('source-backed directory includes engineering first and other agent families',()=>{
 assert.equal(roles.roles.length,11);
 assert.equal(social.roles.length,35);
 assert.equal(social.subagent_templates.length,29);
 assert.equal(social.source_type,'DOCUMENTED_ARCHITECTURE_NOT_RUNTIME');
 assert.equal(social.status,'DEFINED_LOGICAL_ROLES_NOT_INSTALLED');
 const ids=new Set([...roles.roles.map(r=>r.role_id),...social.roles.map(r=>r.id)]);
 assert.equal(ids.size,46);
 assert.equal(social.roles[0].id,'FB-00');
 assert.equal(social.roles.at(-1).id,'FB-34');
});
test('all 60 agent-engine relationships resolve inside the 179-engine canonical registry',()=>{
 const ids=new Set(master.engine_ids);
 assert.equal(master.engine_ids.length,179);
 const links=roles.roles.flatMap(r=>r.engines);
 assert.equal(links.length,60);
 assert(links.every(id=>ids.has(id)));
 assert(roles.roles.every(r=>r.reports_to===null&&r.reports_to_state==='UNRESOLVED'));
 assert(social.roles.every(r=>r.engine_ids.length===0&&r.engine_links_state==='UNRESOLVED'));
});
test('directory allows paging/filtering without hardcoded 11 limit or claiming subagent instances',()=>{
 const api=read('api/cerebro-agent-directory.ts');
 assert.match(api,/PARTIAL_SOURCED_INVENTORY_NOT_ALL_AGENTS/);
 assert.match(api,/known_agent_roles/);
 assert.match(api,/subagent_templates_not_instances/);
 assert.match(api,/total_runtime_instances:null/);
 assert.match(api,/page:\{offset,limit,total:records\.length/);
 assert.match(api,/records:records\.slice\(offset,offset\+limit\)/);
 assert.match(api,/pInt\(q\.get\('limit'\),30,100\)/);
 assert.match(api,/OWNER_SESSION_REQUIRED/);
 assert.match(api,/ctx\?\.actor_code!=='CARLOS-ADMIN'/);
 assert.match(api,/process\.env\.VERCEL_ENV!=='preview'/);
 assert.match(api,/req\.method!=='GET'/);
 assert.match(api,/FENIX_OWNER_ONLY|INVALID_QUERY_OR_SCOPE/);
 assert.doesNotMatch(api,/service_role|SUPABASE_SERVICE_KEY|CF_WORKERS_TOKEN|DATABASE_URL/);
});
