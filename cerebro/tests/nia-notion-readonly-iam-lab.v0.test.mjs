import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const candidate=JSON.parse(fs.readFileSync(new URL('../registry/nia-notion-readonly-iam-lab.v0.json',import.meta.url)));
test('NIA dedicated LAB identity is bounded and independent',()=>{
 assert.equal(candidate.engine_id,'ACTGW-001');
 assert.equal(candidate.environment,'PREPROD');
 assert.equal(candidate.lab_environment,'CEREBRO-NIA-LAB');
 assert.equal(candidate.notion_integration.name,'CEREBRO NIA · Lectura LAB');
 assert.equal(candidate.notion_integration.bot_id,'41b81b1a-756d-8132-b0d6-0027f800e898');
 assert.deepEqual(candidate.allowed_page_ids,['41a81b1a756d815ab877f0d264a6a0d4']);
 assert.equal(candidate.secret_name,'CEREBRO_NIA_NOTION_READ_TOKEN');
 assert.equal(candidate.secret_store,'CLOUDFLARE_WORKER_SECRET');
 assert.equal(candidate.credential_ref_id,'credref:nia-notion-readonly-lab');
 assert.equal(candidate.rights.read_content,true);
 for(const [key,value] of Object.entries(candidate.rights))if(key!=='read_content')assert.equal(value,false);
 assert.deepEqual(candidate.execution_policy.methods,['GET']);
 assert.equal(candidate.execution_policy.additional_cost_eur,0);
 assert.equal(candidate.execution_policy.automated_ai_sessions,false);
 assert.equal(candidate.execution_policy.prod_write,false);
 assert.equal(candidate.state.gateway_live_connected,false);
 assert.equal(candidate.state.gateway_isolated_e2e_verified,true);
 assert.equal(candidate.state.gateway_lab_authorization_verified,true);
 assert.equal(candidate.state.gateway_lab_idempotency_verified,true);
 assert.equal(candidate.state.gateway_lab_audit_verified,true);
 assert.equal(candidate.evidence.actgw.result,'NIA_ACTGW_PHYSICAL_GATE=PASS');
 assert.equal(candidate.evidence.actgw.pass_count,17);
 assert.equal(candidate.evidence.actgw.fail_count,0);
 assert.equal(candidate.evidence.actgw.cleanup.queue_and_consumer_deleted,true);
 assert.equal(candidate.state.bot_page_access_verified,true);
 assert.equal(candidate.state.bot_blocks_access_verified,true);
 assert.equal(candidate.state.provider_write_denial_verified,false);
 assert.equal(candidate.state.queue_trigger_cleaned,true);
 assert.equal(candidate.state.secret_configured,'VERIFIED_ENCRYPTED_CLOUDFLARE_SECRET_NAME_AND_TYPE');
});
test('NIA IAM candidate cannot contain secret values',()=>{
 const text=JSON.stringify(candidate);
 assert.equal(/"token"\s*:|"api_key"\s*:|"secret_value"\s*:/i.test(text),false);
 assert.equal(/\bsecret_[a-zA-Z0-9]{18,}/.test(text),false);
});
