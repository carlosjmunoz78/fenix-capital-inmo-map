import {test,expect} from '@playwright/test';
import fs from 'node:fs';

test('CEREBRO is served by the authenticated SPA route, not a shadow static page',async()=>{
  expect(fs.existsSync('public/cerebro/index.html')).toBe(false);
  const shell=fs.readFileSync('src/CerebroConsoleShell.tsx','utf8');
  expect(shell).toContain("location.pathname.replace(/\\/+$/,'')==='/cerebro'");
  expect(shell).toContain("data?.actor_code==='CARLOS-ADMIN'");
  const guard=fs.readFileSync('src/RouteAccessGuard.tsx','utf8');
  expect(guard).toContain("'/cerebro'");
  expect(guard).toContain('<CerebroConsoleHost/>');
  const host=fs.readFileSync('src/CerebroConsoleHost.tsx','utf8');
  expect(host).toContain("type CerebroView=CerebroPrimaryView|'V0'");
  expect(host).toContain("import CerebroInterfaceBar,{type CerebroPrimaryView} from './CerebroInterfaceBar';");
  expect(host).toContain("if(section==='legacy-v0')return'V0'");
  expect(host).toContain("if(section==='jarvis'||section==='v0')return'JARVIS'");
  expect(host).toContain("if(section==='neuronal'||section==='neural')return'NEURONAL'");
  expect(host).toContain("const workHidden=primaryView==='NAVEGADOR'||primaryView==='NEURONAL'");
  expect(host).toContain("const workSurface=primaryView==='OPERATIVA'?'OPERATIVA':'JARVIS'");
  expect(host).toContain("import CerebroJarvisWorkConsole from './CerebroJarvisWorkConsole';");
  expect(host).toContain('className="cerebro-work-mount cerebro-host-v0"');
  expect(host).toContain('hidden={workHidden}');
  expect(host).toContain('<CerebroJarvisWorkConsole surface={workSurface}/>');
  expect(host).toContain("{primaryView==='NEURONAL'?<CerebroNeuralView/>:null}");
  expect(host).toContain("{primaryView==='NAVEGADOR'?<CerebroBrowserConsole/>:null}");
  expect(host).toContain('<div className="cerebro-host-v0 is-visible"><CerebroConsoleShell/></div>');
  expect(host).not.toContain('CerebroOperativeConsole');
  const work=fs.readFileSync('src/CerebroJarvisWorkConsole.tsx','utf8');
  expect(work).toContain("import CerebroConsoleShell from './CerebroConsoleShell';");
  expect(work).toContain('<CerebroConsoleShell/>');
  expect(work).toContain('fetchCerebroActivity');
  expect(work).not.toContain('querySelector');
  const browserConsole=fs.readFileSync('src/CerebroBrowserConsole.tsx','utf8');
  expect(browserConsole).toContain("document.querySelector<HTMLElement>('.cerebro-host-v0 .cerebro-console')");
  const workCss=fs.readFileSync('src/cerebro-jarvis-work.css','utf8');
  expect(workCss).toContain('--jw-bg:#020a10');
  expect(workCss).toContain('--jw-blue:#2c9cff');
  expect(workCss).toContain('--jw-cyan:#37d9ff');
  expect(workCss).toContain('grid-template-columns:280px minmax(0,1fr) 330px');
  const gateway=fs.readFileSync('supabase/functions/cerebro-console-gateway-v0/index.ts','utf8');
  expect(gateway).toContain('actor==="CARLOS-ADMIN"');
  expect(gateway).toContain('reason:"OWNER_ONLY"');
  const knowledge=fs.readFileSync('supabase/functions/cerebro-console-gateway-v0/knowledge.ts','utf8');
  expect(knowledge).toContain('actorCode!=="CARLOS-ADMIN"');
  expect(knowledge).toContain('SOCIAL_SCHEDULE_DATA_SOURCE_ID');
  expect(knowledge).toContain('Programación Editorial');
  expect(knowledge).toContain('cerebro-social-schedule-read-preprod');
  expect(knowledge).toContain('CEREBRO_SOCIAL_QUEUE');
  expect(knowledge).toContain('texto|copy|contenido|caption|que pone');
  expect(knowledge).toContain('message:result.item.caption');
  expect(knowledge).toContain('content_key?:string');
  expect(knowledge).toContain('(^|[^a-z0-9])x([^a-z0-9]|$)');
  expect(knowledge).toContain('socialPublicationByContext');
  expect(knowledge).toContain('caption:String(item?.caption??"")');
  expect(knowledge).toContain('DOMAIN_CANONICAL');
  expect(knowledge).toContain('Conocimiento financiero canónico · Fénix Uno');
  expect(knowledge).toContain('Company Registry · CEREBRO · Fénix Capital');
  expect(knowledge).toContain('read_context');
  const api=fs.readFileSync('src/cerebroConsoleApi.ts','utf8');
  expect(api).toContain('read_context');
  expect(shell).toContain('readContext');
  const socialReader=fs.readFileSync('supabase/functions/cerebro-social-schedule-read-preprod/index.ts','utf8');
  expect(socialReader).toContain('cerebro_social_queue_preprod');
  expect(socialReader).toContain('SOCIAL_READ');
  const app=fs.readFileSync('src/App.tsx','utf8');
  expect(app).toContain("supabase.auth.getSession()");
  expect(app).toContain("fenix-session-active");
  expect(app).toContain("{label:'CEREBRO',route:'/cerebro',resource:'CEREBRO'}");
  const appGateway=fs.readFileSync('supabase/functions/fenix-app-gateway/index.ts','utf8');
  expect(appGateway).toContain("a==='CARLOS-ADMIN'");
  expect(appGateway).toContain("label:'CEREBRO',route:'/cerebro',resource:'CEREBRO'");
  const profile=fs.readFileSync('src/ProfileShell.tsx','utf8');
  expect(profile).toContain("label:'CEREBRO',route:'/cerebro'");
});
